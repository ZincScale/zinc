// zincpyExcParents is a subset of CPython's builtin exception hierarchy, used
// by zincpyMatch to honor subclass relationships in except clauses.
var zincpyExcParents = map[string]string{
	"ValueError":          "Exception",
	"TypeError":           "Exception",
	"KeyError":            "LookupError",
	"IndexError":          "LookupError",
	"LookupError":         "Exception",
	"ZeroDivisionError":   "ArithmeticError",
	"ArithmeticError":     "Exception",
	"RuntimeError":        "Exception",
	"NotImplementedError": "RuntimeError",
	"StopIteration":       "Exception",
	"AttributeError":      "Exception",
	"OSError":             "Exception",
	"Exception":           "BaseException",
}

// zincpyMatch reports whether a recovered panic value matches an except-clause
// type. An empty type is a bare except (matches anything). A non-zincpyExc
// panic (e.g. a Go runtime error) is treated as an Exception.
func zincpyMatch(exc any, typ string) bool {
	if typ == "" {
		return true
	}
	e, ok := exc.(zincpyExc)
	if !ok {
		return typ == "Exception" || typ == "BaseException"
	}
	for t := e.Type; t != ""; t = zincpyExcParents[t] {
		if t == typ {
			return true
		}
	}
	return false
}

// zincpyRepr is Python's repr() for the value kinds we emit: strings are
// single-quoted, bools are True/False, floats use Python float formatting.
func zincpyRepr(v any) string {
	switch x := v.(type) {
	case string:
		return "'" + x + "'"
	case bool:
		if x {
			return "True"
		}
		return "False"
	case float64:
		return zincpyFloat(x)
	default:
		if s, ok := zincpySeqRepr(v); ok {
			return s
		}
		return fmt.Sprint(v)
	}
}

