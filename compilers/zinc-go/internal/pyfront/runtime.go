// zincpySlice implements Python slicing seq[start:stop:step] on a list, string,
// or tuple. start/stop/step are int or nil (omitted). Negative indices and
// negative step are handled per CPython; the result is a new list/string/tuple.
func zincpySlice(seq, startA, stopA, stepA any) any {
	step := 1
	if stepA != nil {
		step = stepA.(int)
		if step == 0 {
			panic(zincpyExc{"ValueError", "slice step cannot be zero"})
		}
	}
	switch s := seq.(type) {
	case string:
		rs := []rune(s)
		var b strings.Builder
		for _, i := range zincpySliceIndices(len(rs), startA, stopA, step) {
			b.WriteRune(rs[i])
		}
		return b.String()
	case zincpyTuple:
		idxs := zincpySliceIndices(len(s.items), startA, stopA, step)
		out := make([]any, len(idxs))
		for k, i := range idxs {
			out[k] = s.items[i]
		}
		return zincpyTuple{items: out}
	}
	elems := zincpySeq(seq)
	idxs := zincpySliceIndices(len(elems), startA, stopA, step)
	out := make([]any, len(idxs))
	for k, i := range idxs {
		out[k] = elems[i]
	}
	return out
}

// zincpySliceIndices returns the concrete indices a slice selects, mirroring
// CPython's slice.indices(length).
func zincpySliceIndices(n int, startA, stopA any, step int) []int {
	lower, upper := 0, n
	if step < 0 {
		lower, upper = -1, n-1
	}
	clamp := func(i int) int {
		if i < lower {
			return lower
		}
		if i > upper {
			return upper
		}
		return i
	}
	var start, stop int
	if startA == nil {
		if step < 0 {
			start = upper
		} else {
			start = lower
		}
	} else {
		start = startA.(int)
		if start < 0 {
			start += n
		}
		start = clamp(start)
	}
	if stopA == nil {
		if step < 0 {
			stop = lower
		} else {
			stop = upper
		}
	} else {
		stop = stopA.(int)
		if stop < 0 {
			stop += n
		}
		stop = clamp(stop)
	}
	var idxs []int
	if step > 0 {
		for i := start; i < stop; i += step {
			idxs = append(idxs, i)
		}
	} else {
		for i := start; i > stop; i += step {
			idxs = append(idxs, i)
		}
	}
	return idxs
}

// zincpyEnumerate mirrors enumerate(xs): (index, element) 2-tuples.
func zincpyEnumerate(xs any) []any {
	s := zincpySeq(xs)
	out := make([]any, len(s))
	for i, v := range s {
		out[i] = zincpyTuple{items: []any{i, v}}
	}
	return out
}

// zincpyZip mirrors zip(a, b, ...): tuples of corresponding elements, stopping
// at the shortest input.
func zincpyZip(args ...any) []any {
	if len(args) == 0 {
		return nil
	}
	seqs := make([][]any, len(args))
	minLen := -1
	for i, a := range args {
		seqs[i] = zincpySeq(a)
		if minLen < 0 || len(seqs[i]) < minLen {
			minLen = len(seqs[i])
		}
	}
	out := make([]any, minLen)
	for i := 0; i < minLen; i++ {
		tup := make([]any, len(seqs))
		for j := range seqs {
			tup[j] = seqs[j][i]
		}
		out[i] = zincpyTuple{items: tup}
	}
	return out
}

func zincpyAbs(v any) any {
	switch x := v.(type) {
	case int:
		if x < 0 {
			return -x
		}
		return x
	case float64:
		return math.Abs(x)
	case bool:
		if x {
			return 1
		}
		return 0
	}
	panic(zincpyExc{"TypeError", "bad operand type for abs(): " + zincpyTypeName(v)})
}

// zincpyStr mirrors Python's str() for the value kinds the front-end emits.
func zincpyStr(v any) string {
	switch x := v.(type) {
	case float64:
		return zincpyFloat(x)
	case bool:
		if x {
			return "True"
		}
		return "False"
	case string:
		return x
	default:
		if s, ok := zincpySeqRepr(v); ok {
			return s
		}
		return fmt.Sprint(v)
	}
}

// zincpySeqRepr renders a Go slice the way Python repr renders a list:
// [e0, e1, ...] with each element via zincpyRepr (so strings are quoted and
// floats/bools use Python formatting). Returns ok=false for non-slices.
// str(list) and repr(list) are identical in Python, so both paths use this.
func zincpySeqRepr(v any) (string, bool) {
	rv := reflect.ValueOf(v)
	if !rv.IsValid() || rv.Kind() != reflect.Slice {
		return "", false
	}
	var b strings.Builder
	b.WriteByte('[')
	for i := 0; i < rv.Len(); i++ {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(zincpyRepr(rv.Index(i).Interface()))
	}
	b.WriteByte(']')
	return b.String(), true
}

// zincpyFloat formats a float the way CPython's repr/str does for the common
// (non-astronomical) range: shortest round-trip digits, with a decimal point
// forced for integer-valued floats (3 -> "3.0"). Scientific-notation
// threshold differences vs CPython are a known gap for very large/small
// magnitudes.
func zincpyFloat(f float64) string {
	switch {
	case math.IsNaN(f):
		return "nan"
	case math.IsInf(f, 1):
		return "inf"
	case math.IsInf(f, -1):
		return "-inf"
	}
	s := strconv.FormatFloat(f, 'g', -1, 64)
	for i := 0; i < len(s); i++ {
		if s[i] == '.' || s[i] == 'e' {
			return s
		}
	}
	return s + ".0"
}

// zincpyDiv is Python true division: always float, and division by zero raises
// ZeroDivisionError (Go float division would yield +Inf instead).
func zincpyDiv(a, b float64) float64 {
	if b == 0 {
		panic(zincpyExc{"ZeroDivisionError", "division by zero"})
	}
	return a / b
}

// zincpyFloorDiv is Python's // on ints: floor toward negative infinity.
// Go's / truncates toward zero, so the two differ when the operands have
// opposite signs and the division is inexact. Division by zero raises
// ZeroDivisionError (matching CPython, not a Go runtime panic).
func zincpyFloorDiv(a, b int) int {
	if b == 0 {
		panic(zincpyExc{"ZeroDivisionError", "integer division or modulo by zero"})
	}
	q := a / b
	if (a%b != 0) && ((a < 0) != (b < 0)) {
		q--
	}
	return q
}

// zincpyMod is Python's % on ints: the result takes the sign of the divisor.
// Go's % takes the sign of the dividend, so e.g. -7 % 3 is -1 in Go but 2 in
// Python.
func zincpyMod(a, b int) int {
	if b == 0 {
		panic(zincpyExc{"ZeroDivisionError", "integer division or modulo by zero"})
	}
	return ((a % b) + b) % b
}

// zincpyDict is an insertion-ordered map — Python dict semantics. Go's
// built-in map randomizes iteration order, so iteration/keys/values/printing
// would diverge from CPython without tracking insertion order explicitly.
// Keys and values are boxed (any); the front-end inserts type assertions on
// Get where the value type is known.
type zincpyDict struct {
	keys []any
	vals map[any]any
}

func zincpyNewDict() *zincpyDict {
	return &zincpyDict{vals: map[any]any{}}
}

func (d *zincpyDict) Set(k, v any) {
	if _, ok := d.vals[k]; !ok {
		d.keys = append(d.keys, k)
	}
	d.vals[k] = v
}

func (d *zincpyDict) Get(k any) any { return d.vals[k] }

func (d *zincpyDict) Has(k any) bool { _, ok := d.vals[k]; return ok }

func (d *zincpyDict) Len() int { return len(d.keys) }

func (d *zincpyDict) Keys() []any { return d.keys }

// Items returns the dict's (key, value) pairs as 2-tuples, in insertion order,
// for use by a for k, v in d.items() loop.
func (d *zincpyDict) Items() []any {
	out := make([]any, len(d.keys))
	for i, k := range d.keys {
		out[i] = zincpyTuple{items: []any{k, d.vals[k]}}
	}
	return out
}

func (d *zincpyDict) Values() []any {
	vs := make([]any, len(d.keys))
	for i, k := range d.keys {
		vs[i] = d.vals[k]
	}
	return vs
}

// String renders the dict the way CPython's repr does: {'a': 1, 'b': 2},
// keys/values via zincpyRepr, in insertion order.
func (d *zincpyDict) String() string {
	var b strings.Builder
	b.WriteByte('{')
	for i, k := range d.keys {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(zincpyRepr(k))
		b.WriteString(": ")
		b.WriteString(zincpyRepr(d.vals[k]))
	}
	b.WriteByte('}')
	return b.String()
}

// zincpyIn implements Python's "in" membership test, dispatching on the
// container: substring for strings, element search (value equality) for
// lists/tuples, key/element presence for dicts/sets.
func zincpyIn(needle, hay any) bool {
	switch h := hay.(type) {
	case string:
		s, ok := needle.(string)
		return ok && strings.Contains(h, s)
	case []any:
		for _, e := range h {
			if zincpyEq(e, needle) {
				return true
			}
		}
		return false
	case zincpyTuple:
		for _, e := range h.items {
			if zincpyEq(e, needle) {
				return true
			}
		}
		return false
	case *zincpyDict:
		return h.Has(needle)
	case *zincpySet:
		return h.Has(needle)
	}
	rv := reflect.ValueOf(hay)
	if rv.Kind() == reflect.Slice {
		for i := 0; i < rv.Len(); i++ {
			if zincpyEq(rv.Index(i).Interface(), needle) {
				return true
			}
		}
		return false
	}
	panic(zincpyExc{"TypeError", "argument of type " + zincpyTypeName(hay) + " is not iterable"})
}

// zincpySet is a Python set. Backed by insertion-ordered storage for
// deterministic iteration in OUR output; note this differs from CPython's
// hash-ordered iteration, so set iteration/printing order is not guaranteed to
// match CPython (use sorted() for stable output). repr: {a, b}, or set() empty.
type zincpySet struct {
	items []any
	has   map[any]bool
}

func zincpyNewSet() *zincpySet { return &zincpySet{has: map[any]bool{}} }

func zincpySetOf(xs any) *zincpySet {
	s := zincpyNewSet()
	for _, v := range zincpySeq(xs) {
		s.Add(v)
	}
	return s
}

func (s *zincpySet) Add(v any) {
	if !s.has[v] {
		s.has[v] = true
		s.items = append(s.items, v)
	}
}

func (s *zincpySet) Has(v any) bool { return s.has[v] }

func (s *zincpySet) Len() int { return len(s.items) }

func (s *zincpySet) Keys() []any { return s.items }

func (s *zincpySet) Discard(v any) {
	if s.has[v] {
		delete(s.has, v)
		for i, x := range s.items {
			if x == v {
				s.items = append(s.items[:i], s.items[i+1:]...)
				break
			}
		}
	}
}

func (s *zincpySet) Remove(v any) {
	if !s.has[v] {
		panic(zincpyExc{"KeyError", zincpyRepr(v)})
	}
	s.Discard(v)
}

func (s *zincpySet) String() string {
	if len(s.items) == 0 {
		return "set()"
	}
	var b strings.Builder
	b.WriteByte('{')
	for i, v := range s.items {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(zincpyRepr(v))
	}
	b.WriteByte('}')
	return b.String()
}

