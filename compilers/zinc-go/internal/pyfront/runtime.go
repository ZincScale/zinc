// zincpyMatch reports whether a recovered panic value matches an except-clause
// type. An empty type is a bare except (matches anything). A non-zincpyExc
// panic (e.g. a Go runtime error) is treated as an Exception.
func zincpyMatch(exc any, typ string) bool {
	if typ == "" {
		return true
	}
	e, ok := exc.(zincpyExc)
	if !ok {
		return typ == "Exception" || typ == "BaseException"
	}
	for t := e.Type; t != ""; t = zincpyExcParents[t] {
		if t == typ {
			return true
		}
	}
	return false
}

// zincpyRepr is Python's repr() for the value kinds we emit: strings are
